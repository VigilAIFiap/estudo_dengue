DECLARE
    V_EXISTS NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_EXISTS
    FROM USER_TABLES
    WHERE TABLE_NAME = 'VIGIL_DQ_REVIEW_LOG';

    IF V_EXISTS = 0 THEN
        EXECUTE IMMEDIATE q'~
            CREATE TABLE VIGIL_DQ_REVIEW_LOG (
                REVIEW_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                FINDING_ID NUMBER NOT NULL,
                OLD_STATUS VARCHAR2(12 CHAR) NOT NULL,
                NEW_STATUS VARCHAR2(12 CHAR) NOT NULL,
                ACTOR VARCHAR2(128 CHAR) NOT NULL,
                REVIEWED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                NOTE VARCHAR2(1000 CHAR),
                CONSTRAINT FK_VIGIL_DQ_REVIEW_FINDING
                    FOREIGN KEY (FINDING_ID) REFERENCES VIGIL_DQ_FINDING (FINDING_ID),
                CONSTRAINT CK_VIGIL_DQ_REVIEW_OLD_STATUS
                    CHECK (OLD_STATUS IN ('ABERTO', 'EM_ANALISE', 'RESOLVIDO', 'ACEITO')),
                CONSTRAINT CK_VIGIL_DQ_REVIEW_NEW_STATUS
                    CHECK (NEW_STATUS IN ('EM_ANALISE', 'RESOLVIDO', 'ACEITO'))
            )
        ~';
    END IF;
END;
/

DECLARE
    V_EXISTS NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_EXISTS
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'IX_VIGIL_DQ_REVIEW_FINDING';

    IF V_EXISTS = 0 THEN
        EXECUTE IMMEDIATE
            'CREATE INDEX IX_VIGIL_DQ_REVIEW_FINDING '
            || 'ON VIGIL_DQ_REVIEW_LOG (FINDING_ID, REVIEWED_AT)';
    END IF;
END;
/

CREATE OR REPLACE PACKAGE VIGIL_DQ_REVIEW AS
    PROCEDURE REVISAR(
        P_FINDING_ID IN NUMBER,
        P_NEW_STATUS IN VARCHAR2,
        P_NOTE IN VARCHAR2 DEFAULT NULL,
        P_ACTOR IN VARCHAR2 DEFAULT NULL
    );
END VIGIL_DQ_REVIEW;
/

CREATE OR REPLACE PACKAGE BODY VIGIL_DQ_REVIEW AS
    PROCEDURE REVISAR(
        P_FINDING_ID IN NUMBER,
        P_NEW_STATUS IN VARCHAR2,
        P_NOTE IN VARCHAR2 DEFAULT NULL,
        P_ACTOR IN VARCHAR2 DEFAULT NULL
    ) IS
        V_OLD_STATUS VIGIL_DQ_FINDING.STATUS%TYPE;
        V_ACTOR VARCHAR2(128) := SUBSTR(NVL(P_ACTOR, USER), 1, 128);
        V_NEW_STATUS VARCHAR2(12) := UPPER(TRIM(P_NEW_STATUS));
    BEGIN
        IF V_NEW_STATUS IS NULL
            OR V_NEW_STATUS NOT IN ('EM_ANALISE', 'RESOLVIDO', 'ACEITO')
        THEN
            RAISE_APPLICATION_ERROR(-20001, 'Status de revisão inválido.');
        END IF;

        SELECT STATUS
        INTO V_OLD_STATUS
        FROM VIGIL_DQ_FINDING
        WHERE FINDING_ID = P_FINDING_ID
        FOR UPDATE;

        UPDATE VIGIL_DQ_FINDING
        SET STATUS = V_NEW_STATUS,
            REVIEWED_BY = V_ACTOR,
            REVIEWED_AT = SYSTIMESTAMP,
            RESOLUTION_NOTE = SUBSTR(P_NOTE, 1, 1000)
        WHERE FINDING_ID = P_FINDING_ID;

        INSERT INTO VIGIL_DQ_REVIEW_LOG (
            FINDING_ID, OLD_STATUS, NEW_STATUS, ACTOR, NOTE
        ) VALUES (
            P_FINDING_ID, V_OLD_STATUS, V_NEW_STATUS, V_ACTOR,
            SUBSTR(P_NOTE, 1, 1000)
        );
    END REVISAR;
END VIGIL_DQ_REVIEW;
/

COMMIT;
