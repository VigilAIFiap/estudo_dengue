-- Views and manual review workflow for Oracle APEX.
-- Run after sql/create_data_quality_tables.sql.
-- This file replaces the former FAQ/assistant package with a review-only package.

CREATE OR REPLACE VIEW VIGIL_DQ_BATCH_SUMMARY AS
SELECT
    batch.BATCH_ID,
    batch.SOURCE_NAME,
    batch.STARTED_AT,
    batch.FINISHED_AT,
    batch.STATUS,
    batch.ROW_COUNT,
    batch.FINDING_COUNT,
    batch.CREATED_BY,
    SUM(
        CASE
            WHEN finding.STATUS IN ('ABERTO', 'EM_ANALISE') THEN 1
            ELSE 0
        END
    ) OPEN_FINDINGS
FROM VIGIL_DQ_BATCH batch
LEFT JOIN VIGIL_DQ_FINDING finding
    ON finding.BATCH_ID = batch.BATCH_ID
GROUP BY
    batch.BATCH_ID,
    batch.SOURCE_NAME,
    batch.STARTED_AT,
    batch.FINISHED_AT,
    batch.STATUS,
    batch.ROW_COUNT,
    batch.FINDING_COUNT,
    batch.CREATED_BY;

CREATE OR REPLACE VIEW VIGIL_DQ_FINDING_QUEUE AS
SELECT
    finding.FINDING_ID,
    finding.BATCH_ID,
    finding.REGISTRO_ID,
    batch.SOURCE_NAME,
    finding.RULE_CODE,
    finding.FIELD_NAME,
    finding.SEVERITY,
    finding.MESSAGE,
    finding.STATUS,
    finding.DETECTED_AT,
    finding.REVIEWED_BY,
    finding.REVIEWED_AT,
    finding.RESOLUTION_NOTE
FROM VIGIL_DQ_FINDING finding
JOIN VIGIL_DQ_BATCH batch
    ON batch.BATCH_ID = finding.BATCH_ID;

CREATE OR REPLACE VIEW VIGIL_DQ_OPEN_RULE_SUMMARY AS
SELECT
    finding.RULE_CODE,
    rule.FIELD_NAME,
    rule.DESCRIPTION,
    finding.SEVERITY,
    COUNT(*) OPEN_FINDINGS,
    COUNT(DISTINCT finding.BATCH_ID) AFFECTED_BATCHES
FROM VIGIL_DQ_FINDING finding
JOIN VIGIL_DQ_RULE rule
    ON rule.RULE_CODE = finding.RULE_CODE
WHERE finding.STATUS IN ('ABERTO', 'EM_ANALISE')
GROUP BY
    finding.RULE_CODE,
    rule.FIELD_NAME,
    rule.DESCRIPTION,
    finding.SEVERITY;

