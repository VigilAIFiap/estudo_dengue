-- Estrutura inicial para entrada e auditoria no Oracle APEX.
-- Execute uma vez no schema da aplicação; não altera PRATA nem OURO.
-- A tabela de entrada contém dados clínicos sensíveis, mesmo sem identificadores
-- diretos. Restrinja acesso no schema/APEX e defina retenção antes da ingestão.
-- O ID técnico é uma identity; RECEBIDO_EM registra a data/hora separadamente.
-- Campos de entrada são texto para preservar valores inválidos para revisão.

CREATE TABLE VIGIL_DQ_RULE (
    RULE_CODE VARCHAR2(50 CHAR) PRIMARY KEY,
    FIELD_NAME VARCHAR2(30 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(500 CHAR) NOT NULL,
    SEVERITY VARCHAR2(10 CHAR) NOT NULL,
    ACTIVE CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
    CONSTRAINT CK_VIGIL_DQ_RULE_SEV
        CHECK (SEVERITY IN ('INFO', 'ALERTA', 'ERRO')),
    CONSTRAINT CK_VIGIL_DQ_RULE_ACTIVE
        CHECK (ACTIVE IN ('S', 'N'))
);

CREATE TABLE VIGIL_DQ_BATCH (
    BATCH_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    SOURCE_NAME VARCHAR2(200 CHAR) NOT NULL,
    STARTED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    FINISHED_AT TIMESTAMP WITH TIME ZONE,
    STATUS VARCHAR2(12 CHAR) DEFAULT 'EM_ANDAMENTO' NOT NULL,
    ROW_COUNT NUMBER(12) DEFAULT 0 NOT NULL,
    FINDING_COUNT NUMBER(12) DEFAULT 0 NOT NULL,
    CREATED_BY VARCHAR2(128 CHAR) NOT NULL,
    CONSTRAINT CK_VIGIL_DQ_BATCH_STATUS
        CHECK (STATUS IN ('EM_ANDAMENTO', 'CONCLUIDO', 'FALHOU')),
    CONSTRAINT CK_VIGIL_DQ_BATCH_COUNTS
        CHECK (ROW_COUNT >= 0 AND FINDING_COUNT >= 0)
);

CREATE TABLE VIGIL_DQ_RECORD (
    REGISTRO_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    BATCH_ID NUMBER NOT NULL,
    SOURCE_ROW NUMBER(12) NOT NULL,
    RECEBIDO_EM TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    DT_NOTIFIC VARCHAR2(30 CHAR),
    ID_MUNICIP VARCHAR2(12 CHAR),
    IDADE_ANOS VARCHAR2(30 CHAR),
    CS_SEXO VARCHAR2(10 CHAR),
    CS_GESTANT VARCHAR2(20 CHAR),
    FEBRE VARCHAR2(10 CHAR),
    MIALGIA VARCHAR2(10 CHAR),
    CEFALEIA VARCHAR2(10 CHAR),
    EXANTEMA VARCHAR2(10 CHAR),
    VOMITO VARCHAR2(10 CHAR),
    NAUSEA VARCHAR2(10 CHAR),
    DOR_COSTAS VARCHAR2(10 CHAR),
    CONJUNTVIT VARCHAR2(10 CHAR),
    ARTRITE VARCHAR2(10 CHAR),
    ARTRALGIA VARCHAR2(10 CHAR),
    PETEQUIA_N VARCHAR2(10 CHAR),
    DOR_RETRO VARCHAR2(10 CHAR),
    DIABETES VARCHAR2(10 CHAR),
    HEMATOLOG VARCHAR2(10 CHAR),
    HEPATOPAT VARCHAR2(10 CHAR),
    RENAL VARCHAR2(10 CHAR),
    HIPERTENSA VARCHAR2(10 CHAR),
    ACIDO_PEPT VARCHAR2(10 CHAR),
    AUTO_IMUNE VARCHAR2(10 CHAR),
    CONSTRAINT FK_VIGIL_DQ_REC_BATCH
        FOREIGN KEY (BATCH_ID) REFERENCES VIGIL_DQ_BATCH (BATCH_ID),
    CONSTRAINT UK_VIGIL_DQ_REC_BATCH_ROW
        UNIQUE (BATCH_ID, SOURCE_ROW),
    CONSTRAINT UK_VIGIL_DQ_REC_BATCH_ID
        UNIQUE (BATCH_ID, REGISTRO_ID)
);

CREATE TABLE VIGIL_DQ_FINDING (
    FINDING_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    BATCH_ID NUMBER NOT NULL,
    REGISTRO_ID NUMBER NOT NULL,
    RULE_CODE VARCHAR2(50 CHAR) NOT NULL,
    FIELD_NAME VARCHAR2(30 CHAR) NOT NULL,
    SEVERITY VARCHAR2(10 CHAR) NOT NULL,
    MESSAGE VARCHAR2(1000 CHAR) NOT NULL,
    STATUS VARCHAR2(12 CHAR) DEFAULT 'ABERTO' NOT NULL,
    DETECTED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    REVIEWED_BY VARCHAR2(128 CHAR),
    REVIEWED_AT TIMESTAMP WITH TIME ZONE,
    RESOLUTION_NOTE VARCHAR2(1000 CHAR),
    CONSTRAINT FK_VIGIL_DQ_FIND_BATCH
        FOREIGN KEY (BATCH_ID) REFERENCES VIGIL_DQ_BATCH (BATCH_ID),
    CONSTRAINT FK_VIGIL_DQ_FIND_RULE
        FOREIGN KEY (RULE_CODE) REFERENCES VIGIL_DQ_RULE (RULE_CODE),
    CONSTRAINT FK_VIGIL_DQ_FIND_REC_BATCH
        FOREIGN KEY (BATCH_ID, REGISTRO_ID)
        REFERENCES VIGIL_DQ_RECORD (BATCH_ID, REGISTRO_ID),
    CONSTRAINT CK_VIGIL_DQ_FIND_SEV
        CHECK (SEVERITY IN ('INFO', 'ALERTA', 'ERRO')),
    CONSTRAINT CK_VIGIL_DQ_FIND_STATUS
        CHECK (STATUS IN ('ABERTO', 'EM_ANALISE', 'RESOLVIDO', 'ACEITO'))
);

CREATE INDEX IX_VIGIL_DQ_BATCH_STATUS
    ON VIGIL_DQ_BATCH (STATUS, STARTED_AT);

CREATE INDEX IX_VIGIL_DQ_FIND_QUEUE
    ON VIGIL_DQ_FINDING (STATUS, SEVERITY, DETECTED_AT);

CREATE INDEX IX_VIGIL_DQ_FIND_RECORD
    ON VIGIL_DQ_FINDING (BATCH_ID, REGISTRO_ID);

MERGE INTO VIGIL_DQ_RULE target
USING (
    SELECT 'DT_NOTIFIC_INVALIDA' RULE_CODE, 'DT_NOTIFIC' FIELD_NAME,
           'Data de notificação inválida ou ausente.' DESCRIPTION,
           'ERRO' SEVERITY FROM DUAL
    UNION ALL
    SELECT 'DT_NOTIFIC_FUTURA', 'DT_NOTIFIC',
           'Data de notificação posterior à data da validação.', 'ALERTA'
    FROM DUAL
    UNION ALL
    SELECT 'IDADE_FORA_INTERVALO', 'IDADE_ANOS',
           'Idade preenchida fora do intervalo aceito de 0 a 120 anos.', 'ALERTA'
    FROM DUAL
    UNION ALL
    SELECT 'MUNICIPIO_NAO_RECONHECIDO', 'ID_MUNICIP',
           'Código municipal não encontrado na dimensão de municípios.', 'ERRO'
    FROM DUAL
) src
ON (target.RULE_CODE = src.RULE_CODE)
WHEN MATCHED THEN UPDATE SET
    target.FIELD_NAME = src.FIELD_NAME,
    target.DESCRIPTION = src.DESCRIPTION,
    target.SEVERITY = src.SEVERITY
WHEN NOT MATCHED THEN INSERT (
    RULE_CODE, FIELD_NAME, DESCRIPTION, SEVERITY, ACTIVE
) VALUES (
    src.RULE_CODE, src.FIELD_NAME, src.DESCRIPTION, src.SEVERITY, 'S'
);

COMMIT;
