-- Formulário de acolhimento para avaliação de completude no Oracle APEX.
-- Não armazena nome, CPF, endereço, telefone, texto livre ou diagnóstico.
-- Esta é uma fila compartilhada entre API e APEX, não uma GLOBAL TEMPORARY TABLE:
-- os dados precisam permanecer visíveis para o APEX em outra sessão Oracle.
-- Defina prazo de retenção e acesso restrito antes de usar com dados reais.

CREATE TABLE VIGIL_TRIAGE_INTAKE (
    INTAKE_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RECEIVED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    AGE_GROUP VARCHAR2(10 CHAR),
    SEX VARCHAR2(10 CHAR),
    SYMPTOM_DURATION VARCHAR2(12 CHAR),
    FEVER VARCHAR2(3 CHAR),
    HEADACHE VARCHAR2(3 CHAR),
    MUSCLE_PAIN VARCHAR2(3 CHAR),
    RASH VARCHAR2(3 CHAR),
    NAUSEA VARCHAR2(3 CHAR),
    VOMITING VARCHAR2(3 CHAR),
    PREGNANCY VARCHAR2(3 CHAR),
    COMORBIDITIES VARCHAR2(3 CHAR),
    STATUS VARCHAR2(12 CHAR) DEFAULT 'PENDENTE' NOT NULL,
    REVIEWED_BY VARCHAR2(128 CHAR),
    REVIEWED_AT TIMESTAMP WITH TIME ZONE,
    REVIEW_NOTE VARCHAR2(1000 CHAR),
    CONSTRAINT CK_VIGIL_TRIAGE_AGE
        CHECK (AGE_GROUP IS NULL OR AGE_GROUP IN ('0-4', '5-9', '10-19', '20-39', '40-59', '60+')),
    CONSTRAINT CK_VIGIL_TRIAGE_SEX
        CHECK (SEX IS NULL OR SEX IN ('F', 'M', 'OUTRO')),
    CONSTRAINT CK_VIGIL_TRIAGE_DURATION
        CHECK (SYMPTOM_DURATION IS NULL OR SYMPTOM_DURATION IN ('HOJE', '1-3_DIAS', '4+_DIAS')),
    CONSTRAINT CK_VIGIL_TRIAGE_ANSWERS
        CHECK (
            (FEVER IS NULL OR FEVER IN ('SIM', 'NAO'))
            AND (HEADACHE IS NULL OR HEADACHE IN ('SIM', 'NAO'))
            AND (MUSCLE_PAIN IS NULL OR MUSCLE_PAIN IN ('SIM', 'NAO'))
            AND (RASH IS NULL OR RASH IN ('SIM', 'NAO'))
            AND (NAUSEA IS NULL OR NAUSEA IN ('SIM', 'NAO'))
            AND (VOMITING IS NULL OR VOMITING IN ('SIM', 'NAO'))
            AND (PREGNANCY IS NULL OR PREGNANCY IN ('SIM', 'NAO'))
            AND (COMORBIDITIES IS NULL OR COMORBIDITIES IN ('SIM', 'NAO'))
        ),
    CONSTRAINT CK_VIGIL_TRIAGE_STATUS
        CHECK (STATUS IN ('PENDENTE', 'EM_ANALISE', 'CONCLUIDO'))
);

CREATE INDEX IX_VIGIL_TRIAGE_QUEUE
    ON VIGIL_TRIAGE_INTAKE (STATUS, RECEIVED_AT);

CREATE OR REPLACE VIEW VIGIL_TRIAGE_REVIEW_QUEUE AS
SELECT
    INTAKE_ID,
    RECEIVED_AT,
    AGE_GROUP,
    SEX,
    SYMPTOM_DURATION,
    FEVER,
    HEADACHE,
    MUSCLE_PAIN,
    RASH,
    NAUSEA,
    VOMITING,
    PREGNANCY,
    COMORBIDITIES,
    STATUS,
    CASE
        WHEN AGE_GROUP IS NULL
          OR SEX IS NULL
          OR SYMPTOM_DURATION IS NULL
          OR FEVER IS NULL
          OR HEADACHE IS NULL
          OR MUSCLE_PAIN IS NULL
          OR RASH IS NULL
          OR NAUSEA IS NULL
          OR VOMITING IS NULL
          OR PREGNANCY IS NULL
          OR COMORBIDITIES IS NULL
        THEN 'SIM'
        ELSE 'NAO'
    END AS ALERTA_DADOS_FALTANTES,
    LTRIM(
        CASE WHEN AGE_GROUP IS NULL THEN ', FAIXA_ETARIA' END
        || CASE WHEN SEX IS NULL THEN ', SEXO' END
        || CASE WHEN SYMPTOM_DURATION IS NULL THEN ', TEMPO_SINTOMAS' END
        || CASE WHEN FEVER IS NULL THEN ', FEBRE' END
        || CASE WHEN HEADACHE IS NULL THEN ', CEFALEIA' END
        || CASE WHEN MUSCLE_PAIN IS NULL THEN ', DOR_MUSCULAR' END
        || CASE WHEN RASH IS NULL THEN ', ERUPCAO_CUTANEA' END
        || CASE WHEN NAUSEA IS NULL THEN ', NAUSEA' END
        || CASE WHEN VOMITING IS NULL THEN ', VOMITO' END
        || CASE WHEN PREGNANCY IS NULL THEN ', GESTACAO' END
        || CASE WHEN COMORBIDITIES IS NULL THEN ', COMORBIDADES' END,
        ', '
    ) AS CAMPOS_FALTANTES,
    REVIEWED_BY,
    REVIEWED_AT,
    REVIEW_NOTE
FROM VIGIL_TRIAGE_INTAKE
WHERE STATUS IN ('PENDENTE', 'EM_ANALISE');

CREATE OR REPLACE PACKAGE VIGIL_TRIAGE_REVIEW AS
    PROCEDURE REVISAR(
        P_INTAKE_ID IN NUMBER,
        P_NEW_STATUS IN VARCHAR2,
        P_NOTE IN VARCHAR2 DEFAULT NULL,
        P_ACTOR IN VARCHAR2 DEFAULT NULL
    );
END VIGIL_TRIAGE_REVIEW;
/

CREATE OR REPLACE PACKAGE BODY VIGIL_TRIAGE_REVIEW AS
    PROCEDURE REVISAR(
        P_INTAKE_ID IN NUMBER,
        P_NEW_STATUS IN VARCHAR2,
        P_NOTE IN VARCHAR2 DEFAULT NULL,
        P_ACTOR IN VARCHAR2 DEFAULT NULL
    ) IS
        V_NEW_STATUS VARCHAR2(12) := UPPER(TRIM(P_NEW_STATUS));
    BEGIN
        IF V_NEW_STATUS IS NULL
            OR V_NEW_STATUS NOT IN ('EM_ANALISE', 'CONCLUIDO')
        THEN
            RAISE_APPLICATION_ERROR(-20011, 'Status de acolhimento inválido.');
        END IF;

        UPDATE VIGIL_TRIAGE_INTAKE
        SET STATUS = V_NEW_STATUS,
            REVIEWED_BY = SUBSTR(NVL(TRIM(P_ACTOR), USER), 1, 128),
            REVIEWED_AT = SYSTIMESTAMP,
            REVIEW_NOTE = SUBSTR(P_NOTE, 1, 1000)
        WHERE INTAKE_ID = P_INTAKE_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20012, 'Registro de acolhimento não encontrado.');
        END IF;
    END REVISAR;
END VIGIL_TRIAGE_REVIEW;
/

COMMIT;
